export type ErrorCode =
  | 'UNAUTHORIZED' | 'FORBIDDEN' | 'TENANT_RESOURCE_NOT_FOUND' | 'NOT_FOUND' | 'VALIDATION_ERROR'
  | 'AGENCY_INACTIVE' | 'QUOTE_EXPIRED' | 'PRICE_CHANGED' | 'QUOTE_UNAVAILABLE' | 'INSUFFICIENT_FUNDS'
  | 'BOOKING_PROVIDER_SIM_FAILURE' | 'TICKETING_SIM_FAILURE' | 'INVALID_STATE' | 'DUPLICATE_EVENT'
  | 'IDEMPOTENCY_CONFLICT' | 'PNR_NOT_FOUND' | 'PNR_ALREADY_IMPORTED' | 'DOCUMENT_UNREADABLE'
  | 'FX_RATE_UNAVAILABLE' | 'GUIDED_ONLY' | 'INTEGRATION_NOT_CONNECTED' | 'DUPLICATE_RECORD'
  | 'RESET_NOT_ALLOWED' | 'CREDIT_BLOCKED';

const STATUS: Record<ErrorCode, number> = {
  UNAUTHORIZED: 401, FORBIDDEN: 403, TENANT_RESOURCE_NOT_FOUND: 404, NOT_FOUND: 404, VALIDATION_ERROR: 422,
  AGENCY_INACTIVE: 403, QUOTE_EXPIRED: 409, PRICE_CHANGED: 409, QUOTE_UNAVAILABLE: 409, INSUFFICIENT_FUNDS: 422,
  BOOKING_PROVIDER_SIM_FAILURE: 503, TICKETING_SIM_FAILURE: 503, INVALID_STATE: 409, DUPLICATE_EVENT: 409,
  IDEMPOTENCY_CONFLICT: 409, PNR_NOT_FOUND: 404, PNR_ALREADY_IMPORTED: 409, DOCUMENT_UNREADABLE: 422,
  FX_RATE_UNAVAILABLE: 422, GUIDED_ONLY: 409, INTEGRATION_NOT_CONNECTED: 503, DUPLICATE_RECORD: 409,
  RESET_NOT_ALLOWED: 403, CREDIT_BLOCKED: 422,
};
export class AppError extends Error {
  constructor(public code: ErrorCode, message: string, public details?: unknown) { super(message); }
  get status() { return STATUS[this.code] ?? 400; }
}
export const fail = (code: ErrorCode, message: string, details?: unknown): never => { throw new AppError(code, message, details); };
export const NEUTRAL_NOT_FOUND = 'No matching record found for your agency. Verify the reference or contact Hubfares Support.';
